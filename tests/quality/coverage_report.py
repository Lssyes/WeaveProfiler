#!/usr/bin/env python3
"""Turn a coverage.py JSON report of the golden suite into docs/refactor/coverage_main_path.md.

    coverage run --source=weaveprof -m unittest tests/golden/test_golden_audit.py
    coverage json -o coverage_main_path.json
    python3 -B tests/quality/coverage_report.py coverage_main_path.json > docs/refactor/coverage_main_path.md

The report lists, per core module, how many lines the main path (megakernel audit on the golden captures)
executes. Modules at 0% are the first deletion candidates for Phase 2; partially covered ones are where
dead branches hide.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import code_metrics  # noqa: E402


def main() -> int:
    cov = json.loads(Path(sys.argv[1]).read_text())
    files = {}
    for path, data in cov["files"].items():
        rel = Path(path).resolve()
        try:
            rel = rel.relative_to(ROOT)
        except ValueError:
            parts = Path(path).parts
            rel = Path(*parts[parts.index("weaveprof"):]) if "weaveprof" in parts else Path(path)
        s = data["summary"]
        files[rel.as_posix()] = (s["covered_lines"], s["num_statements"])
    _, per_file = code_metrics.collect()
    py_core = {k: v for k, v in per_file.items() if k.startswith("weaveprof/") and k.endswith(".py")}

    rows = []
    for rel, code_lines in py_core.items():
        cov_l, stmts = files.get(rel, (0, None))
        pct = (100.0 * cov_l / stmts) if stmts else 0.0
        rows.append((rel, code_lines, cov_l, stmts, pct))
    zero = [r for r in rows if r[2] == 0]
    part = [r for r in rows if r[2] > 0]
    total_code = sum(r[1] for r in rows)
    zero_code = sum(r[1] for r in zero)

    print("# Main-path coverage (golden suite)\n")
    print("Generated by `tests/quality/coverage_report.py` from `coverage run --source=weaveprof -m unittest "
          "tests/golden/test_golden_audit.py` (3 real H20 captures through `run_megakernel_audit`).\n")
    print(f"- Python core modules: {len(rows)}, {total_code:,} non-blank lines")
    print(f"- Not executed at all by the main path: {len(zero)} modules, {zero_code:,} lines "
          f"({100.0 * zero_code / max(1, total_code):.0f}%)")
    exec_stmts = sum(r[2] for r in part)
    print(f"- Executed statements in the remaining modules: {exec_stmts:,}\n")
    print("## Executed by the main path\n")
    print("| module | non-blank lines | executed statements | statements | executed % |")
    print("|---|---:|---:|---:|---:|")
    for rel, code_lines, cov_l, stmts, pct in sorted(part, key=lambda r: -r[2]):
        print(f"| `{rel}` | {code_lines:,} | {cov_l:,} | {stmts or 0:,} | {pct:.0f}% |")
    print("\n## Not executed by the main path (deletion candidates unless another kept feature needs them)\n")
    print("| module | non-blank lines |")
    print("|---|---:|")
    for rel, code_lines, *_ in sorted(zero, key=lambda r: -r[1]):
        print(f"| `{rel}` | {code_lines:,} |")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
