#!/usr/bin/env python3
"""Locate or fetch a working trace_processor_shell for fast-instrument-v2 G24.

G24 (``weaveprof/pipeline/validate/deliver_gate.py::_check_real_perfetto_import``) imports the
final ``.perfetto.json.gz`` with a REAL ``trace_processor_shell`` and rejects
known import/data-loss stats.  Many hosts ship neither that binary nor the
``perfetto`` python package, which strands every instrumentation target with no
receipt.  This script makes G24's dependency self-service and reproducible.

Order of operations
-------------------
1. PROBE for an already-usable binary, so we never re-download and never touch a
   binary other agents may be depending on:

       ``--tps PATH``  ->  ``$TRACE_PROCESSOR_SHELL``
       ->  ``<out-dir>/trace_processor_shell``  ->  ``trace_processor_shell`` on ``$PATH``

   "usable" == ``--version`` returns rc 0 AND a real minimal G24-style import
   succeeds (rc 0, forbidden stats absent, imported_slices > 0).

2. If none is usable, FETCH the official Perfetto amalgamated bootstrap from
   ``https://get.perfetto.dev/trace_processor``.  That script embeds a
   per-platform manifest (url + file_size + sha256) generated by
   ``weaveprof/pipeline/validate/tools/release/roll-prebuilts``.

3. DOWNLOAD the binary for this host's platform/arch, verifying size + sha256.
   If the current release cannot start on an older glibc host, retry the
   pinned Perfetto v47 linux-x86_64 binary, verify its exact size + sha256,
   and require the same real-import self-check.  The fallback is recorded in
   ``<out-dir>/.TPS_FALLBACK.json``; it is never presented as the latest build.

       *** NETWORK TRAP -- read this ***
       The manifest url points at ``commondatastorage.googleapis.com``, which is
       FIREWALLED on some networks: ``curl`` hangs on connect and exits 28
       (connection timeout) with no proxy available.  The *identical* GCS object
       is also served from ``storage.googleapis.com``, which is reachable.  We
       therefore try the manifest host first with a short ``--connect-timeout``
       so a blocked host fails fast, then RETRY the same object via the alternate
       GCS host.  If BOTH hosts fail we print a precise, human-readable
       diagnostic (every url tried, curl exit code, proxy situation) and exit
       non-zero -- never a silent failure.

4. ``chmod +x``, then run a real minimal import SELF-CHECK (identical SQL to
   G24) to prove the binary actually works before we hand it back.

5. Emit progress on stderr; the ONLY thing written to stdout is the usable
   absolute path (so callers can do ``TPS=$(python3 get_trace_processor.py)``).

Usage
-----
    python3 weaveprof/pipeline/scan/get_trace_processor.py
    python3 weaveprof/pipeline/scan/get_trace_processor.py --out-dir /proj/.instr_v2/_env
    python3 weaveprof/pipeline/scan/get_trace_processor.py --tps /some/trace_processor_shell
    TPS=$(python3 weaveprof/pipeline/scan/get_trace_processor.py) && echo "$TPS"
"""
from __future__ import annotations

import argparse
import ast
import csv
import gzip
import hashlib
import io
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

# Official amalgamated python installer.  This host reaches it fine; it embeds
# the signed per-platform manifest we parse below.
BOOTSTRAP_URL = 'https://get.perfetto.dev/trace_processor'

# GCS serves the same object from two hostnames.  The manifest names the first;
# on networks where it is firewalled (curl exit 28, connect timeout, no proxy)
# the second is the working fallback.  Keyed by EXACT hostname (netloc), not by
# substring: 'storage.googleapis.com' is a substring of
# 'commondatastorage.googleapis.com', so a naive str.replace corrupts the URL.
GCS_HOST_FALLBACKS = {
    'commondatastorage.googleapis.com': 'storage.googleapis.com',
    'storage.googleapis.com': 'commondatastorage.googleapis.com',
}

# curl exit codes that mean the host is genuinely unreachable (DNS, refused,
# connect timeout / firewalled).  Do NOT retry these -- fall straight through to
# the alternate host.  Any other non-zero exit (e.g. 56 SSL EOF, 18 partial
# transfer) is treated as transient and retried on the same host.
_CURL_UNREACHABLE_EXITS = {6, 7, 28}

# Mirrors deliver_gate.py::FORBIDDEN_IMPORT_STATS.  Used only to prove the
# downloaded binary can answer G24's stats query; kept inline so this bootstrap
# has no import dependency on the validate stage.
G24_FORBIDDEN_STATS = (
    'json_parser_failure',
    'json_tokenizer_failure',
    'slice_spill_overlapping_complete_event',
    'slice_drop_overlapping_complete_event',
    'trace_sorter_negative_timestamp_dropped',
)

# Current Perfetto releases are built against newer glibc than some kernel
# workers provide.  v47 is the newest tested release that imports the final
# Chrome-JSON trace on glibc 2.32.  Pin both bytes and provenance.
PINNED_FALLBACKS = {
    ('linux', 'x86_64'): {
        'version': 'v47.0-c74251226',
        'url': ('https://storage.googleapis.com/perfetto-luci-artifacts/'
                'v47.0/linux-amd64/trace_processor_shell'),
        'file_size': 10363488,
        'sha256': '832425c3c7934904d1e0ec1721beb51423de7dbcf399a899973f2b6b464603fa',
    },
}

# platform.machine() varies; normalise to the manifest's `machine` vocabulary.
MACHINE_ALIASES = {
    'x86_64': {'x86_64', 'amd64', 'x64'},
    'amd64': {'x86_64', 'amd64', 'x64'},
    'x64': {'x86_64', 'amd64', 'x64'},
    'aarch64': {'aarch64', 'arm64'},
    'arm64': {'aarch64', 'arm64'},
}


def log(msg: str = '') -> None:
    """All human-facing progress goes to stderr; stdout is reserved for the path."""
    print(msg, file=sys.stderr, flush=True)


# --------------------------------------------------------------------------- #
# Usability probe (shared by "reuse existing" and "verify freshly downloaded")
# --------------------------------------------------------------------------- #
def _g24_sql() -> str:
    names = ',\n    '.join(f"'{name}'" for name in G24_FORBIDDEN_STATS)
    return (
        'WITH bad AS (\n'
        '  SELECT name FROM stats\n'
        '  WHERE value > 0 AND name IN (\n    '
        + names
        + '\n  )\n'
        ')\n'
        'SELECT\n'
        '  (SELECT COUNT(*) FROM bad) AS forbidden_stat_count,\n'
        '  (SELECT GROUP_CONCAT(name) FROM (SELECT name FROM bad ORDER BY name))'
        ' AS forbidden_stats,\n'
        '  (SELECT COUNT(*) FROM slice) AS imported_slices;'
    )


def _parse_import_result(stdout: str):
    """Parse the one-row CSV emitted by trace_processor_shell ``-Q``."""
    try:
        rows = list(csv.DictReader(io.StringIO(stdout or '')))
        row = rows[0] if rows else {}
        forbidden_count = int(row.get('forbidden_stat_count'))
        imported_slices = int(row.get('imported_slices'))
    except (TypeError, ValueError, IndexError):
        return None
    forbidden_stats = row.get('forbidden_stats')
    return forbidden_count, forbidden_stats, imported_slices


def _imported_slices(out: str) -> int:
    parsed = _parse_import_result(out)
    return parsed[2] if parsed is not None else -1


def _build_minimal_trace() -> dict:
    """A minimal legal Perfetto JSON trace: nested, non-overlapping ph=X events."""
    ev = [{'ph': 'M', 'pid': 0, 'tid': 100, 'name': 'thread_name',
           'args': {'name': 'SM0/warp0'}}]
    base = 100000
    for task in range(2):
        t0 = base + task * 500
        ev.append({'ph': 'X', 'pid': 0, 'tid': 100, 'name': f'task{task}',
                   'ts': t0, 'dur': 400, 'args': {'task_id': task}})
        cursor = t0 + 10
        for phase, dur in (('load', 90), ('mma', 150), ('store', 60)):
            ev.append({'ph': 'X', 'pid': 0, 'tid': 100, 'name': phase,
                       'ts': cursor, 'dur': dur, 'args': {'phase': phase}})
            cursor += dur + 2
    return {'traceEvents': ev, 'displayTimeUnit': 'ns',
            'otherData': {'producer': 'get_trace_processor_selftest'}}




def _version_line(tps: Path):
    try:
        proc = subprocess.run([str(tps), '--version'],
                              capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    text = (proc.stdout or proc.stderr or '').strip()
    return text.splitlines()[0] if text else '(no version string)'


def _real_import_ok(tps: Path):
    """Replicate G24's invocation on a fresh clean trace; return (ok, detail)."""
    with tempfile.TemporaryDirectory() as td:
        trace = Path(td) / 'selfcheck.perfetto.json.gz'
        with gzip.open(trace, 'wb') as fh:
            fh.write(json.dumps(_build_minimal_trace()).encode())
        try:
            proc = subprocess.run([str(tps), '-Q', _g24_sql(), str(trace)],
                                  capture_output=True, text=True, timeout=180)
        except (OSError, subprocess.SubprocessError) as exc:
            return False, f'invocation failed: {exc}'
        combined = (proc.stdout or '') + '\n' + (proc.stderr or '')
        if proc.returncode != 0:
            return False, f'rc={proc.returncode}: {combined.strip()[-400:]}'
        parsed = _parse_import_result(proc.stdout or '')
        if parsed is None:
            return False, ('real import did not return integer '
                           f'forbidden_stat_count/imported_slices: '
                           f'{(proc.stdout or "")[-400:]}')
        forbidden_count, forbidden_stats, n = parsed
        fired = [name for name in G24_FORBIDDEN_STATS
                 if name in (forbidden_stats or '')]
        if forbidden_count != 0 or fired:
            return False, (f'clean trace unexpectedly tripped count={forbidden_count} '
                           f'stats={fired or forbidden_stats}')
        if n <= 0:
            return False, f'imported_slices={n} (expected > 0)'
        return True, f'clean import ok, imported_slices={n}, forbidden stats=0'


def is_usable(candidate) -> tuple:
    """Pure probe: does this path point at a working trace_processor_shell?

    Never mutates the candidate (no chmod), so probing a binary other agents own
    is side-effect free.
    """
    if not candidate:
        return False, 'no path'
    path = Path(candidate).expanduser()
    if not path.is_file():
        return False, f'not a file: {path}'
    if not os.access(str(path), os.X_OK):
        return False, f'not executable (chmod +x needed): {path}'
    version = _version_line(path)
    if version is None:
        return False, f'--version failed: {path}'
    ok, detail = _real_import_ok(path)
    if not ok:
        return False, f'self-check failed: {detail}'
    return True, f'{version}; {detail}'


# --------------------------------------------------------------------------- #
# Download with the firewalled-host fallback
# --------------------------------------------------------------------------- #
def _candidate_urls(url: str) -> list:
    """Return [original, alternate-GCS-host] using an EXACT netloc swap."""
    parts = urlsplit(url)
    urls = [url]
    alt_host = GCS_HOST_FALLBACKS.get(parts.netloc)
    if alt_host:
        alt = urlunsplit((parts.scheme, alt_host, parts.path,
                          parts.query, parts.fragment))
        if alt not in urls:
            urls.append(alt)
    return urls


def _download(url: str, dest: Path, connect_timeout: int, max_time: int,
              retries: int = 5, stall_time: int = 60, min_speed: int = 256) -> tuple:
    """Download url -> dest. Prefer curl (matches the documented trap), fall back
    to urllib if curl is unavailable.

    Distinguishes two failure modes that both surface as curl exit 28:
      * a CONNECT failure ("Failed to connect ...") means the host is firewalled
        -> return immediately so the caller falls through to the alternate host;
      * a slow/stalled TRANSFER ("Operation timed out ... bytes received") means
        the host works but is throttled -> retry with HTTP-range resume (-C -)
        so partial bytes are not thrown away.
    We deliberately do NOT pass curl --max-time (it kills a slow-but-progressing
    transfer mid-stream); instead --speed-limit/--speed-time abort only on a real
    stall, and `max_time` bounds each attempt at the subprocess level.
    Return (ok, human_detail)."""
    curl = shutil.which('curl')
    if curl:
        last = 'no attempt made'
        for attempt in range(1, retries + 1):
            argv = [curl, '-fsSL', '-C', '-',
                    '--connect-timeout', str(connect_timeout),
                    '--speed-limit', str(min_speed), '--speed-time', str(stall_time),
                    '-o', str(dest), url]
            try:
                proc = subprocess.run(argv, capture_output=True, text=True,
                                      timeout=max_time)
            except subprocess.TimeoutExpired:
                got = dest.stat().st_size if dest.is_file() else 0
                last = f'hard cap {max_time}s hit with {got} bytes so far'
                continue  # partial bytes kept; resume on next attempt
            if proc.returncode == 0 and dest.is_file() and dest.stat().st_size > 0:
                suffix = f' [attempt {attempt}]' if attempt > 1 else ''
                return True, f'curl ok ({dest.stat().st_size} bytes){suffix}'
            err_lines = [ln for ln in (proc.stderr or '').strip().splitlines() if ln.strip()]
            err = err_lines[-1] if err_lines else '(no stderr)'
            unreachable = (proc.returncode in _CURL_UNREACHABLE_EXITS
                           and ('Failed to connect' in err
                                or 'Could not resolve host' in err
                                or 'Connection refused' in err))
            if unreachable:
                return False, f'curl exit {proc.returncode} (host unreachable/firewalled): {err}'
            got = dest.stat().st_size if dest.is_file() else 0
            last = f'curl exit {proc.returncode} (transient/slow, {got} bytes so far): {err}'
        return False, f'{last} (after {retries} attempts)'
    try:
        import urllib.request
        req = urllib.request.Request(url, headers={'User-Agent': 'get_trace_processor'})
        with urllib.request.urlopen(req, timeout=max_time) as resp, open(dest, 'wb') as fh:
            shutil.copyfileobj(resp, fh)
        if dest.is_file() and dest.stat().st_size > 0:
            return True, f'urllib ok ({dest.stat().st_size} bytes)'
        return False, 'urllib produced an empty file'
    except Exception as exc:  # noqa: BLE001 - report any transport failure verbatim
        return False, f'urllib error: {exc}'


def _diagnose_all_failed(what: str, attempts: list, size=None, sha=None) -> None:
    proxies = [k for k in ('http_proxy', 'https_proxy', 'HTTP_PROXY', 'HTTPS_PROXY',
                           'all_proxy', 'ALL_PROXY') if os.environ.get(k)]
    log('')
    log('=' * 74)
    log(f'[FATAL] could not download the trace_processor {what}: every endpoint failed.')
    for url, ok, detail in attempts:
        log(f'  - {url}')
        log(f'      {detail}')
    log('')
    log('  Likely cause: the primary GCS host commondatastorage.googleapis.com is')
    log('  firewalled here (curl exit 28 / connection timeout) AND the')
    log('  storage.googleapis.com fallback also failed (unreachable, or too slow')
    log('  to finish within the retry budget).')
    log(f'  Proxy env: {", ".join(proxies) if proxies else "NONE set"}')
    log('  Fixes:')
    log('    (a) export https_proxy=<reachable-proxy> and re-run; or')
    log('    (b) on any reachable host download the binary and copy it to')
    log('        <out-dir>/trace_processor_shell, then pass --trace-processor to G24.')
    if size and sha:
        log(f'  Expected linux-amd64 object: size={size} sha256={sha}')
    log('=' * 74)


# --------------------------------------------------------------------------- #
# Manifest parsing + platform selection
# --------------------------------------------------------------------------- #
def _fetch_bootstrap(connect_timeout: int, max_time: int) -> tuple:
    with tempfile.TemporaryDirectory() as td:
        dest = Path(td) / 'trace_processor'
        attempts = []
        for url in _candidate_urls(BOOTSTRAP_URL):
            ok, detail = _download(url, dest, connect_timeout, max_time)
            attempts.append((url, ok, detail))
            if ok:
                return dest.read_text(errors='replace'), attempts
        return None, attempts


def _parse_manifest(text: str):
    marker = re.search(r'TRACE_PROCESSOR_SHELL_MANIFEST\s*=\s*\[', text)
    if not marker:
        return None
    start = text.index('[', marker.start())
    depth = 0
    for i in range(start, len(text)):
        ch = text[i]
        if ch == '[':
            depth += 1
        elif ch == ']':
            depth -= 1
            if depth == 0:
                try:
                    return ast.literal_eval(text[start:i + 1])
                except (ValueError, SyntaxError):
                    return None
    return None


def _select_entry(manifest: list):
    sysplat = sys.platform
    if sysplat.startswith('linux'):
        our_platform = 'linux'
    elif sysplat == 'darwin':
        our_platform = 'darwin'
    elif os.name == 'nt':
        our_platform = 'windows'
    else:
        our_platform = sysplat
    machine = platform.machine().lower()
    aliases = MACHINE_ALIASES.get(machine, {machine})
    for entry in manifest:
        if entry.get('platform') != our_platform:
            continue
        entry_machines = {str(m).lower() for m in (entry.get('machine') or [])}
        if entry_machines & aliases:
            return entry
    return None


# --------------------------------------------------------------------------- #
# Acquire (download + verify + install + self-check)
# --------------------------------------------------------------------------- #
def _pinned_fallback_entry():
    plat = 'linux' if sys.platform.startswith('linux') else sys.platform
    machine = platform.machine().lower()
    aliases = MACHINE_ALIASES.get(machine, {machine})
    for key_machine in sorted(aliases):
        entry = PINNED_FALLBACKS.get((plat, key_machine))
        if entry:
            return dict(entry)
    return None


def _write_path_marker(out_dir: Path, target: Path) -> None:
    try:
        marker = out_dir / f'.TPS_PATH.{os.getpid()}'
        marker.write_text(str(target.resolve()) + '\n', encoding='utf-8')
        os.replace(str(marker), str(out_dir / 'TPS_PATH'))
    except OSError:
        pass


def _acquire_pinned_fallback(out_dir: Path, entry: dict, reason: str,
                             connect_timeout: int, max_time: int):
    version = str(entry['version'])
    url = str(entry['url'])
    size = int(entry['file_size'])
    sha = str(entry['sha256']).lower()
    target = out_dir / 'trace_processor_shell'
    log(f'[fallback] current trace_processor failed self-check: {reason}')
    log(f'[fallback] trying pinned {version} for older glibc: {url}')
    out_dir.mkdir(parents=True, exist_ok=True)
    attempts = []
    with tempfile.TemporaryDirectory(dir=str(out_dir)) as td:
        part = Path(td) / 'trace_processor_shell.part'
        downloaded = False
        for candidate in _candidate_urls(url):
            ok, detail = _download(candidate, part, connect_timeout, max_time)
            attempts.append((candidate, ok, detail))
            log(f'[fallback] GET {candidate} -> {"ok" if ok else "FAIL"}: {detail}')
            if ok:
                downloaded = True
                break
        if not downloaded:
            _diagnose_all_failed(f'pinned {version} binary', attempts, size=size, sha=sha)
            return None
        actual_size = part.stat().st_size
        if actual_size != size:
            log(f'[fallback:verify] SIZE MISMATCH: got {actual_size}, pinned {size}. Refusing.')
            return None
        digest = hashlib.sha256()
        with open(part, 'rb') as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b''):
                digest.update(chunk)
        actual_sha = digest.hexdigest().lower()
        if actual_sha != sha:
            log(f'[fallback:verify] SHA256 MISMATCH: got {actual_sha[:16]}..., '
                f'pinned {sha[:16]}.... Refusing.')
            return None
        part.chmod(0o755)
        ok, detail = is_usable(part)
        if not ok:
            log(f'[fallback:selfcheck] FAILED: {detail}')
            return None
        os.replace(str(part), str(target))
    log(f'[fallback:selfcheck] {detail}')
    log(f'[fallback:install] {target}')
    try:
        (out_dir / '.TPS_FALLBACK.json').write_text(
            json.dumps({
                'version': version,
                'url': url,
                'file_size': size,
                'sha256': sha,
                'reason_current_release_failed_selfcheck': reason,
                'selfcheck': detail,
            }, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    except OSError:
        pass
    _write_path_marker(out_dir, target)
    return target


def acquire(out_dir: Path, connect_timeout: int, max_time: int):
    target = out_dir / 'trace_processor_shell'
    log(f'[fetch] downloading Perfetto amalgamated bootstrap: {BOOTSTRAP_URL}')
    text, boot_attempts = _fetch_bootstrap(connect_timeout, max_time)
    if text is None:
        _diagnose_all_failed('bootstrap installer', boot_attempts)
        return None
    manifest = _parse_manifest(text)
    if not manifest:
        log('[fetch] ERROR: could not parse TRACE_PROCESSOR_SHELL_MANIFEST from the '
            'bootstrap. Perfetto may have changed the installer format.')
        return None
    entry = _select_entry(manifest)
    if not entry:
        available = ', '.join(sorted({e.get('arch', '?') for e in manifest}))
        log(f'[fetch] ERROR: no manifest entry for platform={sys.platform} '
            f'machine={platform.machine()}. Available: {available}')
        return None

    url = str(entry['url'])
    size = int(entry['file_size'])
    sha = str(entry['sha256']).lower()
    log(f'[fetch] manifest arch={entry.get("arch")} size={size} sha256={sha[:16]}...')
    log(f'[fetch] connect-timeout={connect_timeout}s -> a firewalled host fails '
        f'fast, then falls back to the alternate GCS endpoint.')

    out_dir.mkdir(parents=True, exist_ok=True)
    attempts = []
    with tempfile.TemporaryDirectory(dir=str(out_dir)) as td:
        part = Path(td) / 'trace_processor_shell.part'
        downloaded = False
        for candidate in _candidate_urls(url):
            log(f'[fetch] GET {candidate}')
            ok, detail = _download(candidate, part, connect_timeout, max_time)
            attempts.append((candidate, ok, detail))
            log(f'        -> {"ok" if ok else "FAIL"}: {detail}')
            if ok:
                downloaded = True
                break
        if not downloaded:
            _diagnose_all_failed('binary', attempts, size=size, sha=sha)
            return None

        actual_size = part.stat().st_size
        if actual_size != size:
            log(f'[verify] SIZE MISMATCH: got {actual_size}, manifest {size}. Refusing.')
            return None
        digest = hashlib.sha256()
        with open(part, 'rb') as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b''):
                digest.update(chunk)
        actual_sha = digest.hexdigest().lower()
        if actual_sha != sha:
            log(f'[verify] SHA256 MISMATCH: got {actual_sha[:16]}..., '
                f'manifest {sha[:16]}.... Refusing.')
            return None
        log(f'[verify] size {actual_size} ok; sha256 {actual_sha[:16]}... ok')
        part.chmod(0o755)
        os.replace(str(part), str(target))  # atomic within out_dir

    log(f'[install] {target}')
    ok, detail = is_usable(target)
    if not ok:
        log(f'[selfcheck] FAILED after install: {detail}')
        fallback = _pinned_fallback_entry()
        if fallback is None:
            return None
        return _acquire_pinned_fallback(
            out_dir, fallback, detail, connect_timeout, max_time)
    log(f'[selfcheck] {detail}')

    # Record the resolved path for humans/other tooling (fresh install only).
    _write_path_marker(out_dir, target)
    return target


def main() -> int:
    ap = argparse.ArgumentParser(
        description='Locate or fetch a working trace_processor_shell for G24.')
    ap.add_argument('--tps', default=os.environ.get('TRACE_PROCESSOR_SHELL'),
                    help='explicit trace_processor_shell candidate to probe first '
                         '(default: $TRACE_PROCESSOR_SHELL)')
    ap.add_argument('--out-dir', default=os.environ.get('INSTR_V2_ENV_DIR'),
                    help='install/probe directory '
                         '(default: $INSTR_V2_ENV_DIR or <cwd>/.instr_v2/_env)')
    ap.add_argument('--connect-timeout', type=int, default=20,
                    help='per-connection curl timeout in seconds so a firewalled '
                         'host fails fast (default: 20)')
    ap.add_argument('--max-time', type=int, default=600,
                    help='per-attempt hard cap in seconds; a slow transfer that '
                         'hits it is resumed on the next attempt (default: 600)')
    ap.add_argument('--no-download', action='store_true',
                    help='probe only; never touch the network')
    args = ap.parse_args()

    out_dir = (Path(args.out_dir).expanduser().resolve() if args.out_dir
               else (Path.cwd() / '.instr_v2' / '_env'))

    # 1. Probe existing candidates in priority order; reuse the first usable one.
    probes = []
    if args.tps:
        probes.append(('--tps', args.tps))
    probes.append(('out-dir', str(out_dir / 'trace_processor_shell')))
    on_path = shutil.which('trace_processor_shell')
    if on_path:
        probes.append(('PATH', on_path))

    seen = set()
    for label, candidate in probes:
        resolved_candidate = Path(candidate).expanduser()
        key = str(resolved_candidate)
        if key in seen:
            continue
        seen.add(key)
        ok, detail = is_usable(candidate)
        log(f'[probe:{label}] {candidate} -> {"USABLE" if ok else "unusable"}: {detail}')
        if ok:
            resolved = resolved_candidate.resolve()
            log('[ok] reusing existing trace_processor_shell (no download, untouched).')
            print(str(resolved))  # sole stdout line: the usable absolute path
            return 0

    if args.no_download:
        log('[FATAL] no usable trace_processor_shell found and --no-download was set.')
        return 3

    # 2. Fetch, verify, install, self-check.
    target = acquire(out_dir, args.connect_timeout, args.max_time)
    if target is None:
        return 2
    print(str(target.resolve()))  # sole stdout line: the usable absolute path
    return 0


if __name__ == '__main__':
    sys.exit(main())
